SELECT
    COALESCE(b.CUSTOMER_ID, i.CUSTOMER_ID) AS CUSTOMER_ID,

    COALESCE(b.TOTAL_ACCOUNTS, 0) AS TOTAL_ACCOUNTS,
    COALESCE(b.TOTAL_ACCOUNT_BALANCE, 0) AS TOTAL_ACCOUNT_BALANCE,
    b.LATEST_ACCOUNT_OPEN_DATE,

    COALESCE(i.TOTAL_POLICIES, 0) AS TOTAL_POLICIES,
    COALESCE(i.TOTAL_ANNUAL_PREMIUM, 0) AS TOTAL_ANNUAL_PREMIUM,
    COALESCE(i.TOTAL_COVERAGE_AMOUNT, 0) AS TOTAL_COVERAGE_AMOUNT

FROM {{ ref('int_customer_banking') }} b

FULL OUTER JOIN {{ ref('int_customer_insurance') }} i
    ON b.CUSTOMER_ID = i.CUSTOMER_ID
